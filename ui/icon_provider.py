def create_svg_xml(path_content: str, color_hex: str, stroke_width: float = 2.0) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color_hex}" stroke-width="{stroke_width}" '
        f'stroke-linecap="round" stroke-linejoin="round">{path_content}</svg>'
    )


def get_pixmap(icon_name: str, color_hex: str, size: int = 20, stroke_width: float = 2.0) -> QPixmap:
    path = SVG_PATHS.get(icon_name)
    if not path:
        pix = QPixmap(size, size)
        pix.fill(Qt.GlobalColor.transparent)
        return pix

    xml = create_svg_xml(path, color_hex, stroke_width)
    renderer = QSvgRenderer(QByteArray(xml.encode("utf-8")))

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    painter.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
    renderer.render(painter)
    painter.end()

    return pixmap


def get_icon(icon_name: str, color_hex: str, size: int = 20, stroke_width: float = 2.0) -> QIcon:
    return QIcon(get_pixmap(icon_name, color_hex, size, stroke_width))
